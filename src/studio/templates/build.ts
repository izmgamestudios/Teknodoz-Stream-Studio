// src/studio/templates/build.ts
// Pure: TemplateDef + options -> Scene. No browser APIs, fully unit-testable.
import { createLayer, createScene } from "../defaults";
import type { Layer, Scene } from "../types";
import { LOGICAL_H, LOGICAL_W } from "../types";
import type { PanelSpec, Rect, TemplateDef, TemplateOptions } from "./types";

export const TAG_RED = "#e11d2e";
export const FRAME_WHITE = "#ffffff";
const FALLBACK_BG = "#0a0f1e";
const BAR_DARK = "rgba(7,11,24,0.94)";
const FRAME_W = 8;
const TAG_H = 54;
const BANNER_H = 110;
const PLATE_H = 86;
const TICKER_BAR = 90;
const CAPTION_H = 48;
const TOP_H = 96;
const MAX_TEXT = 300;

const HEX = /^#[0-9a-fA-F]{6}$/;

export function normalizeHex(value: string, fallback: string): string {
  const v = value.trim();
  return HEX.test(v) ? v.toLowerCase() : fallback;
}

/** Trim + cap user supplied template text (no markup is ever interpreted). */
export function cleanText(value: string): string {
  return value.replace(/\s+/g, " ").trim().slice(0, MAX_TEXT);
}

/** Asset ids are generated by us (`uid`, `tpl-bg-…`); anything else is dropped. */
const ASSET_ID = /^[A-Za-z0-9_-]{1,128}$/;
function cleanAssetId(v: string | undefined): string | undefined {
  return v !== undefined && ASSET_ID.test(v) ? v : undefined;
}

export function resolveOptions(
  def: TemplateDef,
  patch: Partial<TemplateOptions> = {},
): TemplateOptions {
  const logoAssetId = cleanAssetId(patch.logoAssetId);
  const backgroundAssetId = cleanAssetId(patch.backgroundAssetId);
  return {
    accent: normalizeHex(
      patch.accent ?? def.defaults.accent,
      def.defaults.accent,
    ),
    title: cleanText(patch.title ?? def.defaults.title),
    tag: cleanText(patch.tag ?? def.defaults.tag),
    ticker: cleanText(patch.ticker ?? def.defaults.ticker),
    ...(logoAssetId ? { logoAssetId } : {}),
    ...(backgroundAssetId ? { backgroundAssetId } : {}),
  };
}

function t(rect: Rect) {
  return { x: rect.x, y: rect.y, w: rect.w, h: rect.h, rotation: 0 };
}

function mediaLayer(p: PanelSpec): Layer {
  const common = { name: p.label, transform: t(p.rect) };
  switch (p.kind) {
    case "webcam":
      return createLayer("webcam", common);
    case "guest":
      return createLayer("guest", { ...common, label: p.label });
    case "screen":
      return createLayer("screen", common);
    case "web":
      return createLayer("web", { ...common, frame: p.frame ?? "none" });
  }
}

function placeholder(p: PanelSpec): Layer {
  return createLayer("text", {
    name: `${p.label} (zemin)`,
    transform: t(p.rect),
    text: p.label,
    fontSize: 44,
    color: "rgba(255,255,255,0.5)",
    bold: false,
    align: "center",
    background: "rgba(255,255,255,0.07)",
    style: "plain",
  });
}

function frame(p: PanelSpec): Layer {
  return createLayer("shape", {
    name: `${p.label} (çerçeve)`,
    transform: t(p.rect),
    shape: "rect",
    fill: "transparent",
    stroke: FRAME_WHITE,
    strokeWidth: FRAME_W,
    radius: 0,
    text: "",
  });
}

function bar(
  name: string,
  rect: Rect,
  text: string,
  o: {
    background: string;
    fontSize: number;
    color?: string;
    align?: "left" | "center";
    style?: "plain" | "ticker";
  },
): Layer {
  return createLayer("text", {
    name,
    transform: t(rect),
    text,
    fontSize: o.fontSize,
    color: o.color ?? "#ffffff",
    bold: true,
    align: o.align ?? "left",
    background: o.background,
    style: o.style ?? "plain",
  });
}

/** Approximate width of the tag bar for `text` at 28px bold. */
function tagWidth(text: string, max: number): number {
  return Math.min(max, Math.max(220, text.length * 19 + 72));
}

/**
 * Build the scene for `def`. `backdropAssetId` is the generated dotted background;
 * without it (SSR, no canvas) a flat dark panel is used so the scene is still usable.
 */
export function buildTemplateScene(
  def: TemplateDef,
  patch: Partial<TemplateOptions> = {},
  backdropAssetId?: string,
): Scene {
  const o = resolveOptions(def, patch);
  const layers: Layer[] = [];
  const SW = def.stage?.w ?? LOGICAL_W;
  const SH = def.stage?.h ?? LOGICAL_H;
  const full: Rect = { x: 0, y: 0, w: SW, h: SH };

  if (def.backdrop) {
    layers.push(
      o.backgroundAssetId
        ? createLayer("image", {
            name: "Arka plan (özel)",
            transform: t(full),
            assetId: o.backgroundAssetId,
            fit: "cover",
            locked: true,
          })
        : backdropAssetId
          ? createLayer("image", {
              name: "Arka plan",
              transform: t(full),
              assetId: backdropAssetId,
              locked: true,
            })
          : createLayer("shape", {
              name: "Arka plan",
              transform: t(full),
              shape: "rect",
              fill: FALLBACK_BG,
              strokeWidth: 0,
              radius: 0,
              text: "",
              locked: true,
            }),
    );
  }

  for (const p of def.panels) {
    if (p.kind === "guest" || p.kind === "screen") layers.push(placeholder(p));
    layers.push(mediaLayer(p));
    if (def.frames) layers.push(frame(p));
    if (def.captions) {
      layers.push(
        bar(
          `${p.label} (etiket)`,
          { x: p.rect.x, y: p.rect.y + p.rect.h, w: p.rect.w, h: CAPTION_H },
          p.label,
          { background: o.accent, fontSize: 28 },
        ),
      );
    }
  }

  if (def.topTitle && o.title) {
    layers.push(
      bar("Başlık şeridi", { x: 0, y: 0, w: SW, h: TOP_H }, o.title, {
        background: o.accent,
        fontSize: 48,
      }),
    );
  }

  if (def.lowerThird) {
    const lt = def.lowerThird;
    if (def.topTitle) {
      // The title already lives in the top strip: the lower third is a single name plate.
      if (o.tag)
        layers.push(
          bar("Alt bant", { x: lt.x, y: lt.y, w: lt.w, h: PLATE_H }, o.tag, {
            background: o.accent,
            fontSize: 48,
          }),
        );
    } else {
      let y = lt.y;
      if (o.tag) {
        layers.push(
          bar(
            "Etiket (kırmızı)",
            { x: lt.x, y, w: tagWidth(o.tag, lt.w), h: TAG_H },
            o.tag,
            { background: TAG_RED, fontSize: 28 },
          ),
        );
        y += TAG_H;
      }
      if (o.title)
        layers.push(
          bar("Alt bant", { x: lt.x, y, w: lt.w, h: BANNER_H }, o.title, {
            background: o.accent,
            fontSize: 64,
          }),
        );
    }
  }

  if (o.logoAssetId) {
    layers.push(
      createLayer("image", {
        name: "Logo",
        transform: t(def.logo),
        assetId: o.logoAssetId,
        fit: "contain",
      }),
    );
  }

  if (def.ticker) {
    layers.push(
      bar(
        "Kayan yazı",
        { x: 0, y: SH - TICKER_BAR, w: SW, h: TICKER_BAR },
        o.ticker,
        { background: BAR_DARK, fontSize: 38, style: "ticker" },
      ),
    );
  }

  const scene = createScene(def.name, layers);
  scene.transition = { type: "fade", ms: 400 };
  return scene;
}

/** Guest layers of a scene that currently have no peer assigned (template slots). */
export function emptyGuestSlots(scene: Scene): string[] {
  return scene.layers
    .filter((l) => l.kind === "guest" && l.peerId === "")
    .map((l) => l.id);
}
